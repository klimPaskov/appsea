#!/usr/bin/env python3
from __future__ import annotations

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / '.agents' / 'skills'
SUBAGENTS = ROOT / '.codex' / 'agents'
GENERATED = ROOT / 'docs' / 'generated'


def parse_skill(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding='utf-8')
    match = re.match(r'^---\n(.*?)\n---\n', text, flags=re.S)
    if not match:
        raise ValueError(f'{path}: missing YAML frontmatter')
    metadata: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if ':' not in line:
            continue
        key, value = line.split(':', 1)
        metadata[key.strip()] = value.strip().strip('"').strip("'")
    name = metadata.get('name', '')
    description = metadata.get('description', '')
    if not name or not description:
        raise ValueError(f'{path}: name and description are required')
    if path.parent.name != name:
        raise ValueError(f'{path}: folder name must match skill name {name}')
    return name, description


def load_skills() -> list[tuple[str, str, str]]:
    skills: list[tuple[str, str, str]] = []
    for path in sorted(SKILLS.glob('*/SKILL.md')):
        name, description = parse_skill(path)
        skills.append((name, description, path.relative_to(ROOT).as_posix()))
    names = [item[0] for item in skills]
    if len(names) != len(set(names)):
        raise ValueError('duplicate skill names')
    return skills


def load_subagents() -> list[tuple[str, str, str, str]]:
    agents: list[tuple[str, str, str, str]] = []
    for path in sorted(SUBAGENTS.glob('*.toml')):
        with path.open('rb') as handle:
            data = tomllib.load(handle)
        name = str(data.get('name', '')).strip()
        description = str(data.get('description', '')).strip()
        sandbox = str(data.get('sandbox_mode', '')).strip()
        if not name or not description or not sandbox:
            raise ValueError(f'{path}: name, description, and sandbox_mode are required')
        if path.stem != name:
            raise ValueError(f'{path}: filename must match agent name {name}')
        agents.append((name, description, sandbox, path.relative_to(ROOT).as_posix()))
    names = [item[0] for item in agents]
    if len(names) != len(set(names)):
        raise ValueError('duplicate subagent names')
    return agents


def table_text(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        '| ' + ' | '.join(headers) + ' |',
        '| ' + ' | '.join('---' for _ in headers) + ' |'
    ]
    for row in rows:
        clean = [value.replace('|', '\\|').replace('\n', ' ') for value in row]
        lines.append('| ' + ' | '.join(clean) + ' |')
    return '\n'.join(lines)


def write_catalogs(
    skills: list[tuple[str, str, str]], agents: list[tuple[str, str, str, str]]
) -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    skill_table = table_text(
        ['Skill', 'Use when', 'Path'],
        [[f'`{name}`', description, f'`{path}`'] for name, description, path in skills]
    )
    (GENERATED / 'skill-catalog.md').write_text(
        '# AppSea skill catalog\n\nGenerated by `scripts/sync_agents.py`. Do not edit by hand.\n\n'
        + skill_table
        + '\n',
        encoding='utf-8'
    )

    agent_table = table_text(
        ['Subagent', 'Purpose', 'Sandbox', 'Path'],
        [
            [f'`{name}`', description, f'`{sandbox}`', f'`{path}`']
            for name, description, sandbox, path in agents
        ]
    )
    (GENERATED / 'subagent-catalog.md').write_text(
        '# AppSea subagent catalog\n\nGenerated by `scripts/sync_agents.py`. Do not edit by hand.\n\n'
        + agent_table
        + '\n',
        encoding='utf-8'
    )

    package_names = sorted(
        path.parent.name for path in (ROOT / 'packages').glob('*/package.json')
    )
    app_names = sorted(path.parent.name for path in (ROOT / 'apps').glob('*/package.json'))
    repository_map = f'''# Generated repository map

Generated by `scripts/sync_agents.py`. Do not edit by hand.

- Apps: {', '.join(f'`{name}`' for name in app_names)}
- Packages: {', '.join(f'`{name}`' for name in package_names)}
- Native skills: {len(skills)}
- Codex subagents: {len(agents)}
- Deep product specs: {len(list((ROOT / 'docs/specs/appsea').glob('*.md')))}
- JSON Schemas: {len(list((ROOT / 'schemas').glob('*.json')))}
'''
    (GENERATED / 'repository-map.md').write_text(repository_map, encoding='utf-8')


def replace_block(text: str, name: str, replacement: str) -> str:
    start = f'<!-- BEGIN GENERATED {name} -->'
    end = f'<!-- END GENERATED {name} -->'
    pattern = re.compile(re.escape(start) + r'.*?' + re.escape(end), flags=re.S)
    if not pattern.search(text):
        raise ValueError(f'AGENTS.md missing generated block {name}')
    return pattern.sub(f'{start}\n{replacement}\n{end}', text)


def update_agents(
    skills: list[tuple[str, str, str]], agents: list[tuple[str, str, str, str]]
) -> bool:
    path = ROOT / 'AGENTS.md'
    text = path.read_text(encoding='utf-8')
    # A repository owner may intentionally keep the root guidance file empty
    # and rely on scoped guidance plus the generated catalogs. Preserve that
    # explicit local choice while still refreshing docs/generated above.
    if not text.strip():
        return False
    skill_lines = '\n'.join(f'- `{name}`: {description}' for name, description, _ in skills)
    agent_lines = '\n'.join(
        f'- `{name}` ({sandbox}): {description}'
        for name, description, sandbox, _ in agents
    )
    text = replace_block(text, 'SKILL CATALOG', skill_lines)
    text = replace_block(text, 'SUBAGENT CATALOG', agent_lines)
    path.write_text(text, encoding='utf-8')
    return True


def main() -> int:
    skills = load_skills()
    agents = load_subagents()
    write_catalogs(skills, agents)
    root_updated = update_agents(skills, agents)
    suffix = '' if root_updated else '; preserved empty user-owned AGENTS.md'
    print(f'synced {len(skills)} skills and {len(agents)} subagents{suffix}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
